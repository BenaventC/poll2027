const fs = require("node:fs");
const path = require("node:path");
const { createHash } = require("node:crypto");
const assert = require("node:assert/strict");
const H = require("./model.js");

const parameters = {
  leftMean: -0.45, rightMean: 0.45, leftSigma: 0.22, rightSigma: 0.22, weight: 0.5,
  distribution: "uniform", alpha: 1, beta: 3.5, gamma: 0.1, eta: 0.04,
  scale: 1, kMax: 1.25, noiseSigma: 0.1
};
const seeds = [314159, 271828, 161803];
const horizon = 500;
const seedFor = (seed, turn) => createHash("sha256").update(`pouls:${seed}:${turn}`).digest().readUInt32LE(0);
const mean = values => values.reduce((sum, value) => sum + value, 0) / values.length;
const scenarios = [
  { id: "reference", label: "R\\'ef\\'erence", parameters },
  { id: "sans-reputation", label: "Sans r\\'eputation", parameters: { ...parameters, eta: 0 } },
  { id: "quadratique", label: "Quadratique", parameters: { ...parameters, alpha: 2 } }
];
const compact = round => ({
  noiseSeed: round.noiseSeed, positions: round.positions, scales: round.scales,
  votes: round.votes, turnout: round.turnout, entries: round.entries || [],
  historyLengths: round.historyLengths, shareHistory: round.shareHistory
});

for (const scenario of scenarios) {
  const points = H.distribution(scenario.parameters);
  scenario.runs = seeds.map(seed => {
    let positions = [0, 0, 0, 0], scales = [1, 1, 1, 1];
    const noiseSeed = seedFor(seed, 0);
    const vote = H.evaluate(H.noisePoints(points, positions, scenario.parameters, noiseSeed),
      positions, { ...scenario.parameters, candidateScales: scales });
    let history = [H.expressedShares(vote)];
    let state = { noiseSeed, historyLengths: [1, 1, 1, 1] };
    const initial = compact({ ...vote, ...state, positions, scales, shareHistory: history });
    const rounds = [];
    for (let t = 1; t <= horizon; t++) {
      state = H.runRound(points, positions, { ...scenario.parameters, noiseSeed: seedFor(seed, t) },
        scales, history, [0, 1, 2, 3], state);
      state.scales.forEach(value => assert.ok(Number.isFinite(value) && value > 0));
      assert.ok(Math.abs(state.votes.reduce((sum, value) => sum + value, 0) - state.turnout) < 1e-10);
      state.moves.forEach(move => assert.ok(move.entry || move.displacement <= scenario.parameters.gamma + 1e-12));
      positions = state.positions;
      scales = state.scales;
      history = state.shareHistory;
      rounds.push(compact(state));
    }
    const summary = {
      finalAbstention: 1 - state.turnout,
      meanLast100Abstention: mean(rounds.slice(-100).map(round => 1 - round.turnout)),
      entries: rounds.reduce((sum, round) => sum + round.entries.length, 0),
      finalRankedVotes: [...state.votes].sort((a, b) => b - a)
    };
    console.log(JSON.stringify({ scenario: scenario.id, seed, ...summary }));
    return { seed, initial, rounds, summary };
  });
}
const output = {
  entryModel: "max-abstainer-coverage", noiseModel: "additive-gaussian",
  decisionMode: "simultaneous", integrationPoints: 1600, horizon, seeds,
  seedRule: "SHA-256 of UTF-8 pouls:<seed>:<turn>, first 4 bytes, little-endian uint32",
  scenarios
};
const write = (name, value) => fs.writeFileSync(path.join(__dirname, name), value, "utf8");
write("simulation-results.json", JSON.stringify(output));
const f = value => value.toFixed(1);
let table = "% Generated by node simulation-results.cjs; do not edit.\n";
table += "\\begin{center}\\small\n\\begin{tabular}{lrrrr}\n\\hline\n";
table += "Sc\\'enario & Graine & Abst.\\ $t=500$ & Abst.\\ $401$--$500$ & Entr\\'ees\\\\\n\\hline\n";
for (const scenario of scenarios) {
  for (const run of scenario.runs) {
    table += `${scenario.label} & ${run.seed} & ${f(100 * run.summary.finalAbstention)}\\,\\% & ${f(100 * run.summary.meanLast100Abstention)}\\,\\% & ${run.summary.entries}\\\\\n`;
  }
  table += "\\hline\n";
}
table += "\\end{tabular}\\end{center}\n";
for (const [i, scenario] of scenarios.entries()) {
  const values = scenario.runs.map(run => 100 * run.summary.meanLast100Abstention);
  table += `\\expandafter\\def\\csname abstMean${i}\\endcsname{${f(mean(values))}}\n`;
  table += `\\expandafter\\def\\csname abstMin${i}\\endcsname{${f(Math.min(...values))}}\n`;
  table += `\\expandafter\\def\\csname abstMax${i}\\endcsname{${f(Math.max(...values))}}\n`;
}
write("simulation-summary.tex", table);
const example = scenarios[0].runs[0];
const states = [example.initial, ...example.rounds];
const headers = ["tour", ...["p", "k", "v"].flatMap(prefix => ["A", "B", "C", "D"].map(letter => prefix + letter)), "abstention", "entrees"];
const csv = [headers.join(","), ...states.map((state, t) =>
  [t, ...state.positions, ...state.scales, ...state.votes.map(value => 100 * value),
    100 * (1 - state.turnout), state.entries.length].join(","))].join("\n");
write("simulation-trajectoires.csv", csv + "\n");
write("simulation-video-data.js", "const filmData = " + JSON.stringify({
  parameters, seed: example.seed, states
}) + ";\n");
console.log("Written simulation-results.json, simulation-summary.tex and simulation-trajectoires.csv");
